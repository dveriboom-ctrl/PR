def add_numbers(a, b):
    """Функция для сложения двух чисел"""
    return a + b

def multiply_numbers(a, b):
    """Функция для умножения двух чисел"""
    return a * b

if __name__ == "__main__":
    print("Пример работы функций:")
    print(f"2 + 3 = {add_numbers(2, 3)}")
    print(f"4 * 5 = {multiply_numbers(4, 5)}")